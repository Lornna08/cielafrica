#!/usr/bin/env node
/* SEO build: run after changing photobooks/index.html, the photo book categories
   (assets/pbk/catalog.js) or adding a public page.      node tools/build-seo.js
   1. writes photobooks/<category>.html: the same app as /photobooks, with its own title,
      description, canonical address, social preview text and breadcrumbs, so each
      category can be found on Google on its own (Vercel serves these files before the
      /photobooks/:page rewrite, so the app behaves exactly the same);
   2. rewrites sitemap.xml with the clean addresses (no .html, no trailing slash) and
      last-changed dates taken from git. */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), cp = require('child_process');
const ROOT = path.join(__dirname, '..'), SITE = 'https://cielafrica.com';
const rd = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

/* ---------- 1. photo book category pages ---------- */
const ctx = { console }; ctx.window = ctx; ctx.self = ctx; vm.createContext(ctx);
vm.runInContext(rd('assets/pbk/catalog.js'), ctx);
const C = ctx.PBKCatalog || ctx.PBKC || Object.values(ctx).find(v => v && typeof v === 'object' && Array.isArray(v.CATS));
const CATS = (C && C.CATS) || vm.runInContext('typeof CATS!=="undefined"?CATS:null', ctx);
if (!CATS || !CATS.length) throw new Error('photo book categories not found in assets/pbk/catalog.js');
const base = rd('photobooks/index.html');
const KW = { travel: 'travel photo book', kenya: 'Kenya photo book', event: 'wedding photo book', couple: 'couple photo book', friends: 'friends photo book', baby: 'baby photo book', pets: 'pet photo book', family: 'family photo book', year: 'year in photos book', someone: 'personalised photo book gift' };
const made = [];
CATS.forEach(c => {
  const url = SITE + '/photobooks/' + c.id;
  const H = { travel: 'Travel Photo Books', kenya: 'Kenya Photo Books', event: 'Wedding & Event Photo Books', couple: 'Couple Photo Books', friends: 'Friends Photo Books', baby: 'Baby Photo Books', pets: 'Pet Photo Books', family: 'Family Photo Books', year: 'Year in Photos Books', someone: 'Photo Book Gifts' }[c.id] || c.title;
  const title = H + ' — Personalised A4 Hardcover | Ciel Africa';
  const desc = c.blurb + ' A personalised A4 hardcover (21 × 29.7 cm) you design on your phone, printed in Kenya.';
  const ld = { '@context': 'https://schema.org', '@graph': [
    { '@type': 'CollectionPage', '@id': url + '#page', url, name: c.title, description: desc, isPartOf: { '@id': SITE + '/#website' }, about: { '@id': SITE + '/photobooks#book' }, inLanguage: 'en' },
    { '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Ciel Africa', item: SITE + '/' },
      { '@type': 'ListItem', position: 2, name: 'Photo Books', item: SITE + '/photobooks' },
      { '@type': 'ListItem', position: 3, name: c.name, item: url }] }] };
  let s = base;
  const sub = (re, val, what) => { if (!re.test(s)) throw new Error('photobooks/index.html: ' + what + ' not found'); s = s.replace(re, val); };
  sub(/<title>[^<]*<\/title>/, '<title>' + esc(title) + '</title>', 'title');
  sub(/<meta name="description" content="[^"]*">/, '<meta name="description" content="' + esc(desc) + '">', 'description');
  s = s.replace(/<meta name="keywords" content="[^"]*">\n?/, '');
  sub(/<link rel="canonical" href="[^"]*">/, '<link rel="canonical" href="' + url + '">', 'canonical');
  sub(/<meta property="og:url" content="[^"]*">/, '<meta property="og:url" content="' + url + '">', 'og:url');
  sub(/<meta property="og:title" content="[^"]*">/, '<meta property="og:title" content="' + esc(c.title + ' by Ciel Africa') + '">', 'og:title');
  sub(/<meta property="og:description" content="[^"]*">/, '<meta property="og:description" content="' + esc(c.blurb) + '">', 'og:description');
  sub(/<meta name="twitter:title" content="[^"]*">/, '<meta name="twitter:title" content="' + esc(c.title + ' by Ciel Africa') + '">', 'twitter:title');
  sub(/<meta name="twitter:description" content="[^"]*">/, '<meta name="twitter:description" content="' + esc(c.blurb) + '">', 'twitter:description');
  sub(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, '<script type="application/ld+json">' + JSON.stringify(ld) + '</script>', 'structured data');
  /* the no-script summary describes this category */
  sub(/<div class="pk-hero__copy"><h1>[\s\S]*?<\/h1><p>[\s\S]*?<\/p>/, '<div class="pk-hero__copy"><h1>' + esc(c.title) + '</h1><p>' + esc(c.blurb) + ' Choose a cover, add your photos and personalise every page of an A4 hardcover (21 × 29.7 cm), printed in Kenya and paid with M-Pesa. Looking for a ' + esc(KW[c.id] || c.title.toLowerCase()) + '? Start here.</p>', 'no-script summary');
  s = s.replace('<!doctype html>', '<!doctype html>\n<!-- generated by tools/build-seo.js from photobooks/index.html: edit that file, then run the tool -->').replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- generated by tools/build-seo.js from photobooks/index.html: edit that file, then run the tool -->');
  fs.writeFileSync(path.join(ROOT, 'photobooks', c.id + '.html'), s);
  made.push('photobooks/' + c.id);
});
console.log('photo book category pages: ' + made.length);

/* ---------- 2. sitemap ---------- */
const PAGES = [
  ['', 'index.html', '1.0', 'weekly'], ['services', 'services.html', '0.9'], ['templates', 'templates.html', '0.9'], ['products', 'products.html', '0.9'],
  ['photobooks', 'photobooks/index.html', '0.9', 'weekly'], ['domains', 'domains.html', '0.8'], ['ciel-shop', 'ciel-shop.html', '0.8'],
  ['work', 'work.html', '0.8'], ['about', 'about.html', '0.7'], ['insights', 'insights.html', '0.6'], ['quote', 'quote.html', '0.8'], ['contact', 'contact.html', '0.7'],
  ['c-ledger', 'c-ledger/index.html', '0.7'], ['reside-ke', 'reside-ke/index.html', '0.7'], ['orbit', 'orbit/index.html', '0.6'], ['kintra', 'kintra/index.html', '0.6'], ['pay-kit', 'pay-kit/index.html', '0.6'],
  ['subscribe', 'subscribe.html', '0.4'], ['domains/terms', 'domains-terms.html', '0.3'],
  ['privacy', 'privacy.html', '0.3'], ['terms', 'terms.html', '0.3'], ['cookies', 'cookies.html', '0.2'], ['refunds', 'refunds.html', '0.3'], ['delivery', 'delivery.html', '0.3']
].concat(CATS.map(c => ['photobooks/' + c.id, 'photobooks/index.html', '0.8', 'weekly']));
const today = new Date().toISOString().slice(0, 10);
const dirty = new Set(cp.execSync('git status --porcelain', { cwd: ROOT }).toString().split('\n').map(l => l.slice(3).trim()).filter(Boolean));
const lastmod = f => { if (dirty.has(f)) return today; try { return cp.execSync('git log -1 --format=%cs -- ' + JSON.stringify(f), { cwd: ROOT }).toString().trim() || today; } catch (e) { return today; } };
const xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + PAGES.map(p => {
  if (!fs.existsSync(path.join(ROOT, p[1]))) throw new Error('sitemap: missing ' + p[1]);
  if (/name="robots" content="[^"]*noindex/.test(rd(p[1]))) throw new Error('sitemap: ' + p[1] + ' is noindex');
  return '  <url><loc>' + SITE + '/' + p[0] + '</loc><lastmod>' + lastmod(p[1]) + '</lastmod><changefreq>' + (p[3] || 'monthly') + '</changefreq><priority>' + p[2] + '</priority></url>';
}).join('\n') + '\n</urlset>\n';
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), xml);
console.log('sitemap: ' + PAGES.length + ' addresses');
